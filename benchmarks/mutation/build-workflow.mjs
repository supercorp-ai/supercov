#!/usr/bin/env node
// Prints a one-job GitHub Actions workflow that builds the supercov binary from the
// checked-out tree (`cargo build --profile measure -p supercov`) and saves it in the
// CI cache under mutation-bench-supercov-bin-<key>, for the benchmark's Supercov jobs
// (workflow.mjs) to restore by the same key in a later run.
//
//   node benchmarks/mutation/build-workflow.mjs --runs-on <runner label> > .github/workflows/<file>.yml
//   # then run it with the variable SUPERCOV_BIN_KEY=<key>, and the benchmark with the same key
//
// The key should name the tree, e.g. a hash of crates/, runtime/ and Cargo.*: a run with
// an existing key restores nothing new and the build is a no-op for cargo.

import { parseArgs } from 'node:util';

const { values: args } = parseArgs({ options: { 'runs-on': { type: 'string' } } });
if (!args['runs-on']) throw new Error('--runs-on <runner label> is required');

const lines = [
  'name: Mutation benchmark - Supercov build',
  '',
  '# Generated by benchmarks/mutation/build-workflow.mjs; see benchmarks/mutation/README.md.',
  '',
  'on:',
  '  workflow_dispatch:',
  '',
  'jobs:',
  '  build:',
  `    runs-on: ${args['runs-on']}`,
  '    timeout-minutes: 11',
  '    steps:',
  '      - uses: actions/checkout@v6',
  '      - uses: dtolnay/rust-toolchain@1.95.0',
  '      - uses: actions/cache/restore@v4',
  '        with:',
  '          path: target',
  '          key: mutation-bench-measure-target-v1-${{ vars.SUPERCOV_BIN_KEY }}',
  '          restore-keys: mutation-bench-measure-target-v1-',
  '      # The restored build may be older than this tree while the files keep their old',
  '      # modification times: make the sources newer so cargo rebuilds what changed.',
  '      - name: Make this tree\'s sources newer than the restored build',
  '        run: git ls-files -z -- crates runtime | xargs -0 touch',
  '      - name: Build',
  '        run: |',
  '          cargo build --profile measure -p supercov',
  '          mkdir -p "$RUNNER_TEMP/supercov-bin"',
  '          cp target/measure/supercov "$RUNNER_TEMP/supercov-bin/supercov"',
  '          "$RUNNER_TEMP/supercov-bin/supercov" --version',
  '      - uses: actions/cache/save@v4',
  '        with:',
  '          path: ${{ runner.temp }}/supercov-bin',
  '          key: mutation-bench-supercov-bin-${{ vars.SUPERCOV_BIN_KEY }}',
  '      - uses: actions/cache/save@v4',
  '        if: ${{ !cancelled() }}',
  '        with:',
  '          path: target',
  '          key: mutation-bench-measure-target-v1-${{ vars.SUPERCOV_BIN_KEY }}',
  '',
];
process.stdout.write(lines.join('\n'));
