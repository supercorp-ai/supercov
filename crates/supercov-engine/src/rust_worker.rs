/// The module wrangler bundles in place of the project's own entry: it
/// installs the registry, then is the project's entry.
const ENTRY_FILE: &str = "supercov-worker-entry.mjs";
const REGISTRY_FILE: &str = "supercov-worker-registry.mjs";

/// Remember every wasm instance the isolate creates, for the inspector:
/// workerd answers no heap queries, so instances cannot be found later.
const REGISTRY: &str = r#"// Generated by Supercov: remembers this isolate's wasm instances.
const instances = (globalThis.__supercovWasm ??= []);
const Instance = WebAssembly.Instance;
function Recorded(module, imports) {
  const instance = new Instance(module, imports);
  instances.push(instance);
  return instance;
}
Recorded.prototype = Instance.prototype;
WebAssembly.Instance = Recorded;
const instantiate = WebAssembly.instantiate;
WebAssembly.instantiate = async function (source, imports) {
  const result = await instantiate.call(WebAssembly, source, imports);
  instances.push(result instanceof Instance ? result : result.instance);
  return result;
};
"#;

/// Evaluated in the Worker's context on every poll: each instrumented
/// crate's region as its header and the pages a probe touched since the
/// last take, then cleared. A region with nothing new is left out, except
/// the first time, which carries what `cfg!` said of the crate's gates.
const TAKE: &str = r#"(() => {
  const seen = (globalThis.__supercovTaken ??= new WeakSet());
  const out = [];
  for (const instance of globalThis.__supercovWasm ?? []) {
    const exports = instance.exports;
    for (const name of Object.keys(exports)) {
      if (!name.startsWith('__supercov_region_')) continue;
      const crate = name.slice('__supercov_region_'.length);
      const packed = BigInt.asUintN(64, BigInt(exports[name]()));
      const at = Number(packed >> 32n), length = Number(packed & 0xffffffffn);
      if (!length || !exports.memory) continue;
      const view = new DataView(exports.memory.buffer, at, length);
      const first = !seen.has(exports);
      if (!first && view.getUint32(40, true) === 0 && view.getUint32(44, true) === 0) continue;
      seen.add(exports);
      const bytes = new Uint8Array(exports.memory.buffer, at, length);
      const encode = (from, to) => {
        let text = '';
        for (let index = from; index < to; index += 0x8000)
          text += String.fromCharCode.apply(null, bytes.subarray(index, Math.min(to, index + 0x8000)));
        return btoa(text);
      };
      const bodyAt = view.getUint32(32, true);
      const segments = [[0, encode(0, bodyAt)]];
      for (let page = 0; bodyAt + page * 4096 < length; page++) {
        if (bytes[128 + (page >> 3)] & (1 << (page & 7))) {
          const from = bodyAt + page * 4096;
          segments.push([from, encode(from, Math.min(length, from + 4096))]);
        }
      }
      out.push([crate, length, segments]);
      exports['__supercov_clear_' + crate]();
    }
  }
  return out;
})()"#;

/// How often the poller takes the regions. A window shorter than the gap
/// between two tests is what lets each be credited its own.
const POLL_INTERVAL: Duration = Duration::from_millis(5);

/// How long a take may go unanswered before it is given up.
const TAKE_PATIENCE: Duration = Duration::from_secs(5);

/// A wrangler configuration Supercov can point at its entry.
#[derive(Debug, Clone, PartialEq, Eq)]
struct WorkerConfig {
    path: PathBuf,
    main: String,
    inspector_port: Option<u16>,
}

/// The wrangler configurations under `root` that build a Rust Worker: a
/// `[build] command` running `worker-build`, beside the crate's Cargo.toml.
///
/// A plain walk: a `.gitignore` above the project (a monorepo's, or the
/// checkout a fixture sits in) must not hide the project itself.
fn worker_configs(root: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    collect_worker_configs(root, 0, &mut found);
    found.sort();
    found
}

/// The Worker configurations in `directory` and, to six levels, below it.
fn collect_worker_configs(directory: &Path, depth: usize, found: &mut Vec<PathBuf>) {
    const SKIPPED: &[&str] = &[
        "node_modules",
        "target",
        "build",
        "dist",
        ".git",
        ".supercov",
        ".wrangler",
    ];
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            continue;
        };
        let Ok(kind) = fs::file_type(&entry) else {
            continue;
        };
        if kind.is_dir() {
            if depth < 6 && !SKIPPED.contains(&name) {
                collect_worker_configs(&path, depth + 1, found);
            }
            continue;
        }
        if !kind.is_file() || !matches!(name, "wrangler.toml" | "wrangler.json" | "wrangler.jsonc")
        {
            continue;
        }
        let builds_rust = read_config(&path).is_some_and(|(_, document)| {
            build_command(&document).is_some_and(|command| command.contains("worker-build"))
        });
        if builds_rust && path.with_file_name("Cargo.toml").is_file() {
            found.push(path);
        }
    }
}

/// A configuration as JSON whatever it was written in.
#[track_caller]
fn read_config(path: &Path) -> Option<(String, Value)> {
    let text = fs::read_to_string(path).ok()?;
    let document = if path
        .extension()
        .is_some_and(|extension| extension == "toml")
    {
        let table = text.parse::<toml::Table>().ok()?;
        serde_json::to_value(table).expect("a TOML table is JSON")
    } else {
        serde_json::from_str(&strip_jsonc(&text)).ok()?
    };
    Some((text, document))
}

fn build_command(document: &Value) -> Option<String> {
    match document.get("build")?.get("command")? {
        Value::String(command) => Some(command.clone()),
        Value::Array(parts) => Some(
            parts
                .iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join(" "),
        ),
        _ => None,
    }
}

fn parse_config(path: &Path) -> Option<WorkerConfig> {
    let (_, document) = read_config(path)?;
    Some(WorkerConfig {
        path: path.to_owned(),
        main: document.get("main")?.as_str()?.to_owned(),
        inspector_port: document
            .get("dev")
            .and_then(|dev| dev.get("inspector_port"))
            .and_then(Value::as_u64)
            .and_then(|port| u16::try_from(port).ok()),
    })
}

/// JSON with comments and trailing commas, as wrangler.jsonc allows, made
/// plain JSON. Strings are copied as they are.
fn strip_jsonc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut characters = text.chars().peekable();
    while let Some(character) = characters.next() {
        match character {
            '"' => {
                out.push('"');
                while let Some(inner) = characters.next() {
                    out.push(inner);
                    match inner {
                        '\\' => {
                            if let Some(escaped) = characters.next() {
                                out.push(escaped);
                            }
                        }
                        '"' => break,
                        _ => {}
                    }
                }
            }
            '/' if characters.peek() == Some(&'/') => {
                characters.next();
                for inner in characters.by_ref() {
                    if inner == '\n' {
                        out.push('\n');
                        break;
                    }
                }
            }
            '/' if characters.peek() == Some(&'*') => {
                characters.next();
                let mut previous = '\0';
                for inner in characters.by_ref() {
                    if previous == '*' && inner == '/' {
                        break;
                    }
                    previous = inner;
                }
            }
            _ => out.push(character),
        }
    }
    // A comma before a closing bracket, past any whitespace.
    let mut cleaned = String::with_capacity(out.len());
    let mut in_string = false;
    let mut escaped = false;
    let bytes = out.as_bytes();
    for (index, character) in out.char_indices() {
        if in_string {
            cleaned.push(character);
            if escaped {
                escaped = false;
            } else if character == '\\' {
                escaped = true;
            } else if character == '"' {
                in_string = false;
            }
            continue;
        }
        if character == '"' {
            in_string = true;
        } else if character == ',' {
            let next = bytes[index + 1..]
                .iter()
                .find(|byte| !byte.is_ascii_whitespace());
            if matches!(next, Some(b'}' | b']')) {
                continue;
            }
        }
        cleaned.push(character);
    }
    cleaned
}

/// Point the copy's configuration at the entry module and, given one, the
/// inspector port. The rest of the configuration is the project's.
fn rewrite_config(config: &WorkerConfig, entry: &str, port: Option<u16>) -> Result<(), String> {
    let path = &config.path;
    let text = fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))?;
    let rewritten = if path
        .extension()
        .is_some_and(|extension| extension == "toml")
    {
        let mut document = text
            .parse::<toml_edit::DocumentMut>()
            .map_err(|error| format!("{}: {error}", path.display()))?;
        document["main"] = toml_edit::value(entry);
        if let (None, Some(port)) = (config.inspector_port, port) {
            if !document.contains_key("dev") {
                document["dev"] = toml_edit::table();
            }
            document["dev"]["inspector_port"] = toml_edit::value(i64::from(port));
        }
        document.to_string()
    } else {
        let mut document: Value = serde_json::from_str(&strip_jsonc(&text))
            .map_err(|error| format!("{}: {error}", path.display()))?;
        document["main"] = json!(entry);
        if let (None, Some(port)) = (config.inspector_port, port) {
            if !document.get("dev").is_some_and(Value::is_object) {
                document["dev"] = json!({});
            }
            document["dev"]["inspector_port"] = json!(port);
        }
        serde_json::to_string_pretty(&document).expect("plain data serializes")
    };
    fs::write(path, rewritten).map_err(|error| format!("{}: {error}", path.display()))
}

/// Write the registry and Supercov's entry beside a configuration and point
/// the configuration at it. A configuration that already names the entry --
/// a copy kept from an earlier run -- is left as it is: the entry would
/// otherwise import itself.
fn point_at_entry(config: &WorkerConfig, port: Option<u16>) -> Result<(), String> {
    if config.main.trim_start_matches("./") == ENTRY_FILE {
        return Ok(());
    }
    let directory = config.path.parent().unwrap_or(Path::new("."));
    fs::write(directory.join(REGISTRY_FILE), REGISTRY).map_err(|error| error.to_string())?;
    let main = config.main.trim_start_matches("./");
    let entry = format!(
        "// Generated by Supercov: the project's entry, with its wasm instances remembered.\nimport './{REGISTRY_FILE}';\nexport * from './{main}';\nexport {{ default }} from './{main}';\n"
    );
    fs::write(directory.join(ENTRY_FILE), entry).map_err(|error| error.to_string())?;
    rewrite_config(config, ENTRY_FILE, port)
}

/// A port nothing listens on now.
fn free_port() -> Result<u16, String> {
    let listener = TcpListener::bind("127.0.0.1:0").map_err(|error| error.to_string())?;
    listener
        .local_addr()
        .map(|address| address.port())
        .map_err(|error| error.to_string())
}

/// The cfg values of wasm32-unknown-unknown, as the crate's own toolchain
/// reports them: what decides which items the target leaves out.
pub(crate) fn wasm_target_cfg(
    crate_directory: &Path,
) -> Option<crate::rust_instrumenter::TargetCfg> {
    let output = std::process::Command::new("rustc")
        .args(["--print", "cfg", "--target", "wasm32-unknown-unknown"])
        .current_dir(crate_directory)
        .launch_output()
        .ok()?;
    target_cfg_of(&output)
}

/// How the Rust Worker in `package` -- a wrangler configuration beside its
/// Cargo.toml whose build runs worker-build -- compiles its crate: for wasm,
/// never as a test, as a release build unless the command asks for `--dev`,
/// with the features the command and the package's own defaults enable.
/// None for a package that is no Worker, or where rustc cannot say what
/// wasm is.
pub(crate) fn worker_build_cfg(
    package: &Path,
    features: &BTreeMap<String, Vec<String>>,
) -> Option<crate::rust_instrumenter::TargetCfg> {
    let command = ["wrangler.toml", "wrangler.json", "wrangler.jsonc"]
        .iter()
        .filter_map(|name| read_config(&package.join(name)))
        .filter_map(|(_, document)| build_command(&document))
        .find(|command| command.contains("worker-build"))?;
    let target = wasm_target_cfg(package)?;
    let words = command.split_whitespace().collect::<Vec<_>>();
    Some(target.for_build(
        false,
        words.contains(&"--dev"),
        enabled_features(&words, features),
    ))
}

/// The features a build command enables in a package with `features`:
/// those it names, the package's defaults unless it says not to, and what
/// each of those enables in turn.
fn enabled_features(words: &[&str], features: &BTreeMap<String, Vec<String>>) -> BTreeSet<String> {
    if words.contains(&"--all-features") {
        return features.keys().cloned().collect();
    }
    let mut pending = Vec::new();
    if !words.contains(&"--no-default-features") {
        pending.push("default".to_owned());
    }
    for (index, word) in words.iter().enumerate() {
        let named = match word.split_once('=') {
            Some(("--features", list)) => Some(list),
            _ if matches!(*word, "--features" | "-F") => words.get(index + 1).copied(),
            _ => None,
        };
        pending.extend(
            named
                .into_iter()
                .flat_map(|list| list.split(','))
                .filter(|name| !name.is_empty())
                .map(str::to_owned),
        );
    }
    let mut enabled = BTreeSet::new();
    while let Some(feature) = pending.pop() {
        // `dep:name` turns on a dependency, not a feature; `name/feature` a
        // dependency's feature, and `name` with it unless written `name?/`.
        let feature = match feature.split_once('/') {
            Some((name, _)) if !name.ends_with('?') => name.to_owned(),
            Some(_) => continue,
            None => feature,
        };
        if feature.starts_with("dep:") || !features.contains_key(&feature) {
            continue;
        }
        if enabled.insert(feature.clone()) {
            pending.extend(features[&feature].iter().cloned());
        }
    }
    enabled
}

/// The cfg values `rustc --print cfg` answered with, if it answered.
fn target_cfg_of(output: &std::process::Output) -> Option<crate::rust_instrumenter::TargetCfg> {
    if !output.status.success() {
        return None;
    }
    let values = String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|line| line.parse::<cargo_platform::Cfg>().ok())
        .collect::<Vec<_>>();
    Some(crate::rust_instrumenter::TargetCfg::new(&values))
}

fn now_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|elapsed| elapsed.as_millis() as i64)
        .unwrap_or(0)
}

/// Takes the regions of one `wrangler dev` through its inspector until told
/// to stop, appending a window per take with anything in it.
struct Poller {
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}

impl Poller {
    /// Through wrangler's inspector, which shows the Worker it was started
    /// for.
    fn start(port: u16, windows: PathBuf) -> Self {
        Self::start_at(port, "/ws".to_owned(), windows)
    }

    /// Through the inspector at `path` on `port`: workerd's own shows each
    /// Worker at `/core:user:<name>`.
    fn start_at(port: u16, path: String, windows: PathBuf) -> Self {
        let stop = Arc::new(AtomicBool::new(false));
        let flag = Arc::clone(&stop);
        let thread = std::thread::Builder::new()
            .name("supercov-worker-poller".into())
            .spawn(move || poll(port, &path, &windows, &flag))
            .ok();
        Self { stop, thread }
    }

    /// Take once more if wrangler is still there, then stop.
    fn finish(mut self) {
        self.stop.store(true, Ordering::Release);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

impl Drop for Poller {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Release);
    }
}

fn poll(port: u16, path: &str, windows: &Path, stop: &AtomicBool) {
    let Ok(mut file) = fs::open_with(fs::OpenOptions::new().create(true).append(true), windows)
    else {
        return;
    };
    let address = SocketAddr::from(([127, 0, 0, 1], port));
    // wrangler starts when the suite asks for it, and restarts the Worker on
    // a rebuild: connect, and connect again, until the run is over.
    while !stop.load(Ordering::Acquire) {
        let Ok(stream) = TcpStream::connect_timeout(&address, Duration::from_millis(200)) else {
            std::thread::sleep(Duration::from_millis(100));
            continue;
        };
        let _ = stream.set_nodelay(true);
        let _ = stream.set_read_timeout(Some(Duration::from_millis(20)));
        let Ok((mut socket, _)) =
            tungstenite::client::client(format!("ws://127.0.0.1:{port}{path}"), stream)
        else {
            std::thread::sleep(Duration::from_millis(100));
            continue;
        };
        session(&mut socket, &mut file, stop);
        let _ = socket.close(None);
    }
}

/// One inspector connection: enable the runtime, learn the Worker's
/// execution context, and take its regions on the clock. Returns when the
/// connection ends, or after the last take once the run is over.
fn session(socket: &mut tungstenite::WebSocket<TcpStream>, file: &mut fs::File, stop: &AtomicBool) {
    session_with_patience(socket, file, stop, TAKE_PATIENCE);
}

/// `session`, giving up on a take unanswered for `patience`.
fn session_with_patience(
    socket: &mut tungstenite::WebSocket<TcpStream>,
    file: &mut fs::File,
    stop: &AtomicBool,
    patience: Duration,
) {
    use tungstenite::{Error, Message};
    let send = |socket: &mut tungstenite::WebSocket<TcpStream>, message: Value| {
        socket
            .send(Message::text(message.to_string()))
            .map_err(|_| ())
    };
    if send(socket, json!({"id": 1, "method": "Runtime.enable"})).is_err() {
        return;
    }
    let mut contexts = Vec::<i64>::new();
    let mut next_id = 2_u64;
    // The take in flight: its id, when it was sent, and where its window
    // starts.
    let mut awaiting: Option<(u64, Instant)> = None;
    let mut window_start = now_ms();
    let mut last_take = Instant::now() - POLL_INTERVAL;
    let mut final_sent = false;
    loop {
        let stopping = stop.load(Ordering::Acquire);
        if stopping && awaiting.is_none() && (final_sent || contexts.is_empty()) {
            return;
        }
        if awaiting.is_none()
            && let Some(context) = contexts.last()
            && (stopping || last_take.elapsed() >= POLL_INTERVAL)
        {
            let id = next_id;
            next_id += 1;
            let request = json!({
                "id": id,
                "method": "Runtime.evaluate",
                "params": {"expression": TAKE, "contextId": context, "returnByValue": true},
            });
            if send(socket, request).is_err() {
                return;
            }
            awaiting = Some((id, Instant::now()));
            last_take = Instant::now();
            final_sent = stopping;
        }
        match socket.read() {
            Ok(Message::Text(text)) => {
                let Ok(message) = serde_json::from_str::<Value>(text.as_str()) else {
                    continue;
                };
                match message.get("method").and_then(Value::as_str) {
                    Some("Runtime.executionContextCreated") => {
                        if let Some(id) = message["params"]["context"]["id"].as_i64() {
                            contexts.push(id);
                        }
                    }
                    Some("Runtime.executionContextDestroyed") => {
                        if let Some(id) = message["params"]["executionContextId"].as_i64() {
                            contexts.retain(|context| *context != id);
                        }
                    }
                    Some("Runtime.executionContextsCleared") => contexts.clear(),
                    _ => {}
                }
                if let Some((id, _)) = awaiting
                    && message.get("id").and_then(Value::as_u64) == Some(id)
                {
                    awaiting = None;
                    let end = now_ms();
                    let regions = &message["result"]["result"]["value"];
                    if regions
                        .as_array()
                        .is_some_and(|regions| !regions.is_empty())
                    {
                        let line = json!({"start": window_start, "end": end, "regions": regions});
                        let _ = writeln!(file, "{line}");
                    }
                    window_start = end;
                }
            }
            Ok(Message::Close(_)) => return,
            Ok(_) => {}
            Err(Error::Io(error))
                if matches!(
                    error.kind(),
                    std::io::ErrorKind::WouldBlock | std::io::ErrorKind::TimedOut
                ) => {}
            Err(_) => return,
        }
        // A take the Worker never answered (it was replaced mid-evaluation)
        // is given up; the next one covers the same span.
        if awaiting.is_some_and(|(_, sent)| sent.elapsed() > patience) {
            awaiting = None;
        }
    }
}

/// A preload for wrangler's Node process: once the runtime is up, it notes
/// where workerd's own inspector listens in a file of the directory
/// `SUPERCOV_WRANGLER_INSPECTORS` names. wrangler's inspector shows one
/// Worker of a `wrangler dev`; workerd's shows every Worker it runs, so a
/// session started with several `-c` is read there whole.
const INSPECTOR_HOOK: &str = r#"'use strict';
// Supercov: where workerd's inspector listens, for the poller of a measured
// `wrangler dev`. Inert in any process that never loads miniflare.
const directory = process.env.SUPERCOV_WRANGLER_INSPECTORS;
if (directory) {
  const Module = require('module');
  const fs = require('fs');
  const path = require('path');
  const load = Module._load;
  Module._load = function (request) {
    const exports = load.apply(this, arguments);
    const Miniflare = request === 'miniflare' && exports && exports.Miniflare;
    if (Miniflare && !Object.hasOwn(Miniflare.prototype, '__supercov')) {
      Object.defineProperty(Miniflare.prototype, '__supercov', { value: true });
      const inspectorURL = Miniflare.prototype.getInspectorURL;
      Miniflare.prototype.getInspectorURL = async function () {
        const url = await inspectorURL.apply(this, arguments);
        try {
          const file = path.join(directory, process.pid + '.inspector');
          fs.writeFileSync(file + '.tmp', JSON.stringify({ url: String(url) }));
          fs.renameSync(file + '.tmp', file);
        } catch {}
        return url;
      };
    }
    return exports;
  };
}
"#;

/// Where the hook's notes go.
pub const INSPECTORS_ENV: &str = "SUPERCOV_WRANGLER_INSPECTORS";
const HOOK_FILE: &str = "supercov-wrangler-hook.cjs";

/// Writes the hook into `directory`, and says where it is.
#[track_caller]
fn write_hook(directory: &Path) -> Result<PathBuf, String> {
    let hook = directory.join(HOOK_FILE);
    fs::write(&hook, INSPECTOR_HOOK).map_err(|error| format!("{}: {error}", hook.display()))?;
    Ok(hook)
}

/// `NODE_OPTIONS` that load `hook` after what `inherited` already asks.
fn hooked_node_options(inherited: Option<&str>, hook: &Path) -> String {
    let hook = hook.display().to_string();
    // Node splits NODE_OPTIONS at spaces, except inside double quotes.
    let require = if hook.contains(' ') {
        format!("--require=\"{hook}\"")
    } else {
        format!("--require={hook}")
    };
    inherited
        .filter(|options| !options.trim().is_empty())
        .map_or_else(|| require.clone(), |options| format!("{options} {require}"))
}

/// The user Workers workerd's inspector on `port` shows, by their target id
/// (`core:user:<name>`): its `/json` list.
fn inspector_targets(port: u16) -> Vec<String> {
    use std::io::Read;
    let address = SocketAddr::from(([127, 0, 0, 1], port));
    let Ok(mut stream) = TcpStream::connect_timeout(&address, Duration::from_millis(200)) else {
        return Vec::new();
    };
    let _ = stream.set_read_timeout(Some(Duration::from_secs(1)));
    let mut response = Vec::new();
    // A request that cannot be written gets no answer to read.
    let _ = stream.write_all(b"GET /json HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n");
    let _ = stream.read_to_end(&mut response);
    let response = String::from_utf8_lossy(&response);
    // The list whole, whatever framing carries it.
    let list = response
        .find('[')
        .zip(response.rfind(']'))
        .and_then(|(start, end)| response.get(start..=end))
        .and_then(|list| serde_json::from_str::<Vec<Value>>(list).ok())
        .unwrap_or_default();
    list.iter()
        .filter_map(|target| target["id"].as_str())
        .filter(|id| id.starts_with("core:user:"))
        .map(str::to_owned)
        .collect()
}

/// The port of an inspector URL the hook noted: `ws://127.0.0.1:<port>`.
fn inspector_port(url: &str) -> Option<u16> {
    url.trim_end_matches('/')
        .rsplit(':')
        .next()
        .unwrap_or_default()
        .parse()
        .ok()
}

/// Reads every Worker of each `wrangler dev` whose notes land in a
/// directory, through workerd's inspector, each into a windows file of its
/// own, until told to stop. The one wrangler's inspector shows is read there
/// too: each take clears what it read, so every hit is in one file or the
/// other, credited alike.
struct OtherWorkers {
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<Vec<PathBuf>>>,
}

impl OtherWorkers {
    /// `windows` names the file of the nth Worker read.
    fn start(notes: PathBuf, windows: impl Fn(usize) -> PathBuf + Send + 'static) -> Self {
        let stop = Arc::new(AtomicBool::new(false));
        let flag = Arc::clone(&stop);
        let thread = std::thread::Builder::new()
            .name("supercov-worker-others".into())
            .spawn(move || watch_other_workers(&notes, &windows, &flag))
            .ok();
        Self { stop, thread }
    }

    /// Stop, and say which files were written.
    fn finish(mut self) -> Vec<PathBuf> {
        self.stop.store(true, Ordering::Release);
        self.thread
            .take()
            .and_then(|thread| thread.join().ok())
            .unwrap_or_default()
    }
}

impl Drop for OtherWorkers {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Release);
    }
}

fn watch_other_workers(
    notes: &Path,
    windows: &dyn Fn(usize) -> PathBuf,
    stop: &AtomicBool,
) -> Vec<PathBuf> {
    let mut pollers = BTreeMap::<(u16, String), Poller>::new();
    let mut written = Vec::new();
    while !stop.load(Ordering::Acquire) {
        let noted = fs::read_dir(notes)
            .map(|entries| {
                entries
                    .filter_map(Result::ok)
                    .map(|entry| entry.path())
                    .filter(|path| {
                        path.extension()
                            .is_some_and(|extension| extension == "inspector")
                    })
                    .collect::<Vec<_>>()
            })
            .unwrap_or_default();
        for note in noted {
            let Some(note) = fs::read_to_string(&note)
                .ok()
                .and_then(|text| serde_json::from_str::<Value>(&text).ok())
            else {
                continue;
            };
            let Some(port) = note["url"].as_str().and_then(inspector_port) else {
                continue;
            };
            for target in inspector_targets(port) {
                let key = (port, target.clone());
                if pollers.contains_key(&key) {
                    continue;
                }
                let file = windows(written.len());
                pollers.insert(
                    key,
                    Poller::start_at(port, format!("/{target}"), file.clone()),
                );
                written.push(file);
            }
        }
        std::thread::sleep(Duration::from_millis(100));
    }
    for poller in pollers.into_values() {
        poller.finish();
    }
    written
}

/// One take as the poller appended it.
struct Window {
    start: i64,
    end: i64,
    /// Each region, rebuilt: crate key and bytes.
    regions: Vec<(String, Vec<u8>)>,
}

fn read_windows(directory: &Path) -> Result<Vec<Window>, String> {
    let mut files = fs::read_dir(directory)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|entry| entry.path())
                .filter(|path| {
                    path.extension()
                        .is_some_and(|extension| extension == "windows")
                })
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    files.sort();
    let mut windows = Vec::new();
    for file in &files {
        let text =
            fs::read_to_string(file).map_err(|error| format!("{}: {error}", file.display()))?;
        // A line cut short by Supercov being stopped mid-write is skipped.
        for line in text.lines() {
            let Ok(value) = serde_json::from_str::<Value>(line) else {
                continue;
            };
            if let Some(window) = window_from(&value) {
                windows.push(window);
            }
        }
    }
    Ok(windows)
}

fn window_from(value: &Value) -> Option<Window> {
    Some(Window {
        start: value.get("start")?.as_i64()?,
        end: value.get("end")?.as_i64()?,
        regions: crate::rust_wasm::regions_from(value)?,
    })
}

/// The Rust Workers of one Cargo workspace a browser suite may start.
pub struct RustWorkerServer {
    project: PreparedRustProject,
    pollers: Vec<Poller>,
    /// Every Worker of a `wrangler dev`, read through workerd's inspector.
    others: OtherWorkers,
    hook: PathBuf,
    notes: PathBuf,
    integrity: RunIntegrity,
    source_inputs: crate::source_manifest::Inputs,
    source_roots: Option<Vec<String>>,
    /// `.supercov/work/<run>/rust-worker`, holding `evidence/`.
    directory: PathBuf,
}

impl RustWorkerServer {
    /// Whether `root` holds a Rust Worker a suite could start.
    pub fn present(root: &Path) -> bool {
        !worker_configs(root).is_empty()
    }

    /// Instrument the copy's Worker crates and point their configurations at
    /// Supercov's entry, one server per Cargo workspace. Empty when the
    /// project has no Rust Worker.
    pub fn prepare(
        root: &Path,
        workspace: &Path,
        run_id: &str,
        command: &[String],
        diagnostics: &mut dyn Write,
    ) -> Result<Vec<Self>, String> {
        let configs = worker_configs(workspace);
        // Configurations by the Cargo workspace their crate belongs to: a
        // workspace is instrumented once, whatever number of Workers it holds.
        let mut by_workspace = BTreeMap::<PathBuf, Vec<WorkerConfig>>::new();
        for path in configs {
            let Some(config) = parse_config(&path) else {
                let _ = writeln!(
                    diagnostics,
                    "[supercov] {} names no `main`; its Worker is not measured",
                    path.display()
                );
                continue;
            };
            let crate_directory = path.parent().unwrap_or(workspace).to_owned();
            let cargo_root = cargo_workspace_root(&crate_directory).unwrap_or(crate_directory);
            by_workspace.entry(cargo_root).or_default().push(config);
        }
        let mut servers = Vec::new();
        for (index, (cargo_root, configs)) in by_workspace.into_iter().enumerate() {
            let Ok(relative) = cargo_root.strip_prefix(workspace) else {
                continue;
            };
            let source_roots = crate::source_discovery::configured_source_roots(
                &std::env::vars().collect::<BTreeMap<_, _>>(),
            );
            // The project's inputs, as a later query recomputes them to judge
            // whether the run is current.
            let mut integrity_inputs = crate::rust_run::collect_integrity_inputs(root, command)?;
            crate::source_discovery::fold_roots_into_configuration(
                &mut integrity_inputs.execution_configuration,
                source_roots.as_deref(),
            );
            let source_inputs =
                crate::source_capture::capture(root, "rust", integrity_inputs.assertion_paths())?;
            let integrity = create_explicit_run_integrity(
                root,
                &integrity_inputs,
                &FrontendIntegrityInputs::embedded_rust(),
            )
            .map_err(|error| error.to_string())?;
            let cfg = wasm_target_cfg(&cargo_root);
            let mut project =
                crate::rust_project::prepare_rust_project_for(&cargo_root, None, cfg.as_ref())
                    .map_err(|error| error.to_string())?;
            crate::rust_wasm_evidence::root_paths(&mut project, relative);
            let directory = root
                .join(".supercov/work")
                .join(run_id)
                .join(format!("rust-worker-{index}"));
            let evidence = directory.join("evidence");
            fs::create_dir_all(&evidence).map_err(|error| error.to_string())?;
            let hook = write_hook(&directory)?;
            let notes = directory.join("inspectors");
            fs::create_dir_all(&notes).map_err(|error| error.to_string())?;
            let others = {
                let evidence = evidence.clone();
                OtherWorkers::start(notes.clone(), move |number| {
                    evidence.join(format!("other-{number:04}.windows"))
                })
            };
            let mut pollers = Vec::new();
            // Grouped from the configurations, so a workspace has one at least.
            configs
                .iter()
                .enumerate()
                .try_for_each(|(number, config)| -> Result<(), String> {
                    let port = match config.inspector_port {
                        Some(port) => port,
                        None => free_port()?,
                    };
                    point_at_entry(config, Some(port))?;
                    pollers.push(Poller::start(
                        port,
                        evidence.join(format!("{number:04}.windows")),
                    ));
                    Ok(())
                })?;
            servers.push(Self {
                project,
                pollers,
                others,
                hook,
                notes,
                integrity,
                source_inputs,
                source_roots,
                directory,
            });
        }
        Ok(servers)
    }

    pub fn source_files(&self) -> usize {
        self.project.source_files.len()
    }

    /// The source this Worker was instrumented from: an image built from an
    /// earlier copy holds probes placed in other source.
    pub fn source_fingerprint(&self) -> String {
        self.integrity.fingerprint.source.clone()
    }

    /// What the suite's environment needs: a lint on the rewritten source
    /// must not fail the Worker's build under the crate's own lint policy.
    ///
    /// Capped at `warn`, not `allow` as for `cargo test`: Cargo learns which
    /// crate types a target supports from rustc's "dropping unsupported crate
    /// type" warnings, and wasm32 drops `dylib` and `proc-macro`, so with
    /// every lint allowed it cannot read the answer and stops the build. The
    /// probes' parentheses, the one lint they raise, are allowed by name.
    ///
    /// And wrangler's Node process loads the hook that says where workerd's
    /// inspector is, for every Worker of a session, one started with several
    /// `-c`; the suite's own `NODE_OPTIONS` come first.
    pub fn environment(&self) -> BTreeMap<String, String> {
        BTreeMap::from([
            (
                "RUSTFLAGS".into(),
                worker_rustflags(&std::env::var("RUSTFLAGS").unwrap_or_default()),
            ),
            (INSPECTORS_ENV.into(), self.notes.display().to_string()),
            ("NODE_OPTIONS".into(), hooked_node_options(None, &self.hook)),
        ])
    }

    /// Publish what the Workers ran as a Rust run of its own: each window
    /// credited, by time, to the one browser test whose span it overlaps;
    /// what no single test's does is the run's background. None when no
    /// Worker ran or no browser test reported.
    pub fn publish(
        mut self,
        root: &Path,
        _evidence_run_id: &str,
        metadata: RunMetadata,
        served: &[ServedTest],
        diagnostics: &mut dyn Write,
    ) -> Result<Option<(PathBuf, RunMetadata)>, String> {
        // One per configuration, and there is one at least.
        std::mem::take(&mut self.pollers)
            .into_iter()
            .for_each(|poller| {
                poller.finish();
            });
        self.others.finish();
        let evidence_directory = self.directory.join("evidence");
        let result = read_windows(&evidence_directory).and_then(|windows| {
            crate::rust_wasm_evidence::publish(
                root,
                crate::rust_wasm_evidence::WasmRun {
                    language: "Rust Worker",
                    archive: "rust-worker-evidence.raw.gz",
                    project: &self.project,
                    integrity: &self.integrity,
                    source_inputs: &self.source_inputs,
                    source_roots: self.source_roots.clone(),
                },
                windows
                    .into_iter()
                    .map(|window| crate::rust_wasm_evidence::WasmRecord {
                        owner: crate::rust_wasm_evidence::Owner::Window(window.start, window.end),
                        regions: window.regions,
                    })
                    .collect(),
                metadata,
                served,
                diagnostics,
            )
        });
        let result = result.map_err(|error| {
            let run = self
                .directory
                .parent()
                .and_then(Path::file_name)
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default();
            note_kept_evidence(
                root,
                &evidence_directory,
                &format!("{run}-rust-worker"),
                error,
            )
        });
        let _ = remove_stored_tree_deferred(root, &self.directory);
        result
    }
}

/// The program Supercov's `wrangler` stands in for, named in the test
/// processes' environment.
pub const REAL_WRANGLER: &str = "SUPERCOV_WRANGLER";
/// The hook the stand-in has wrangler's Node process load.
pub const HOOK_ENV: &str = "SUPERCOV_WRANGLER_HOOK";
/// The hidden commands the stand-in and its poller run as.
pub const WRANGLER_COMMAND: &str = "__wrangler";
pub const WRANGLER_POLL_COMMAND: &str = "__wrangler-poll";

/// The Rust Workers a `cargo test` suite starts itself, with `wrangler dev`.
///
/// The crate is instrumented with the rest of the workspace, and `wrangler
/// dev` builds it in the copy as it builds it anywhere. What it ran is read
/// by a `wrangler` of Supercov's, first on the test processes' `PATH`: it
/// starts a poller on an inspector port of its own and then becomes the real
/// `wrangler`, so the test keeps the process and the signals it expects. The
/// poller writes what it takes into the evidence directory of the test that
/// started the Worker, and the run reads it there as that test's own: exact,
/// not credited by time.
pub struct CargoTestWorkers {
    environment: Vec<(String, std::ffi::OsString)>,
}

impl CargoTestWorkers {
    /// Put the stand-in in `tools`. None where the workspace has no Rust
    /// Worker, or where no `wrangler` is installed: a test that looks for one
    /// must find none, as it would without Supercov.
    ///
    /// The copy's configurations are left as the project wrote them: a test
    /// may read one as a template for its own. The stand-in wraps whatever
    /// configuration a test's `wrangler dev` is given, as it starts.
    pub fn prepare(workspace: &Path, tools: &Path) -> Result<Option<Self>, String> {
        if worker_configs(workspace).is_empty() {
            return Ok(None);
        }
        let path = std::env::var_os("PATH").unwrap_or_default();
        let Some(real) = on_path(&path, "wrangler") else {
            return Ok(None);
        };
        let supercov = std::env::current_exe().map_err(|error| error.to_string())?;
        fs::create_dir_all(tools).map_err(|error| format!("{}: {error}", tools.display()))?;
        write_stand_in(tools, &supercov)?;
        let hook = write_hook(tools)?;
        let mut directories = vec![tools.to_owned()];
        directories.extend(std::env::split_paths(&path));
        let joined = std::env::join_paths(directories).map_err(|error| error.to_string())?;
        Ok(Some(Self {
            environment: vec![
                ("PATH".into(), joined),
                (REAL_WRANGLER.into(), real.into_os_string()),
                (HOOK_ENV.into(), hook.into_os_string()),
            ],
        }))
    }

    /// What each test process is started with.
    pub fn environment(&self) -> impl Iterator<Item = (&str, &std::ffi::OsStr)> {
        self.environment
            .iter()
            .map(|(name, value)| (name.as_str(), value.as_os_str()))
    }
}

/// A program on `path`: a file of that name, or on Windows one with a
/// PATHEXT extension.
fn on_path(path: &std::ffi::OsStr, name: &str) -> Option<PathBuf> {
    #[cfg(windows)]
    let names = [
        format!("{name}.cmd"),
        format!("{name}.exe"),
        name.to_owned(),
    ];
    #[cfg(not(windows))]
    let names = [name.to_owned()];
    std::env::split_paths(path).find_map(|directory| {
        names
            .iter()
            .map(|name| directory.join(name))
            .find(|candidate| fs::metadata(candidate).is_ok_and(|metadata| metadata.is_file()))
    })
}

fn write_stand_in(tools: &Path, supercov: &Path) -> Result<(), String> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let quoted = supercov.to_string_lossy().replace('\'', r"'\''");
        let script = tools.join("wrangler");
        fs::write(
            &script,
            format!("#!/bin/sh\nexec '{quoted}' {WRANGLER_COMMAND} \"$@\"\n"),
        )
        .map_err(|error| format!("{}: {error}", script.display()))?;
        fs::set_permissions(&script, fs::Permissions::from_mode(0o755))
            .map_err(|error| format!("{}: {error}", script.display()))?;
    }
    #[cfg(windows)]
    {
        let script = tools.join("wrangler.cmd");
        fs::write(
            &script,
            format!("@\"{}\" {WRANGLER_COMMAND} %*\r\n", supercov.display()),
        )
        .map_err(|error| format!("{}: {error}", script.display()))?;
    }
    Ok(())
}

/// `wrangler dev`, with options before or after the command: wrangler's
/// global options that take a value (`--cwd worker dev`) are read past.
fn starts_dev(arguments: &[std::ffi::OsString]) -> bool {
    const VALUED: &[&str] = &["--cwd", "-c", "--config", "-e", "--env", "--env-file"];
    let mut arguments = arguments.iter().map(|argument| argument.to_string_lossy());
    while let Some(argument) = arguments.next() {
        if VALUED.contains(&argument.as_ref()) {
            arguments.next();
        } else if !argument.starts_with('-') {
            return argument == "dev";
        }
    }
    false
}

/// `wrangler dev --remote` (or `-r`): the Worker runs on Cloudflare's edge,
/// and wrangler opens no inspector into it there, so nothing can read what
/// it runs.
fn runs_remote(arguments: &[std::ffi::OsString]) -> bool {
    arguments.iter().any(|argument| {
        matches!(
            argument.to_string_lossy().as_ref(),
            "--remote" | "-r" | "--remote=true"
        )
    })
}

/// The name of the note a test's `wrangler dev --remote` leaves in its
/// evidence.
const REMOTE_NOTE: &str = "worker-remote-";

/// Whether a test, by its evidence, started a Worker with `wrangler dev
/// --remote`.
pub fn started_remote(directory: &Path) -> bool {
    fs::read_dir(directory).is_ok_and(|entries| {
        entries.filter_map(Result::ok).any(|entry| {
            entry
                .file_name()
                .to_str()
                .is_some_and(|name| name.starts_with(REMOTE_NOTE))
        })
    })
}

/// The inspector port the arguments name, as `--inspector-port N` or
/// `--inspector-port=N`.
fn named_inspector_port(arguments: &[std::ffi::OsString]) -> Option<u16> {
    let mut arguments = arguments.iter().map(|argument| argument.to_string_lossy());
    while let Some(argument) = arguments.next() {
        if argument == "--inspector-port" {
            return arguments.next()?.parse().ok();
        }
        if let Some(port) = argument.strip_prefix("--inspector-port=") {
            return port.parse().ok();
        }
    }
    None
}

/// Supercov's `wrangler`: under a test, `wrangler dev` gets an inspector
/// port and a poller writing into the test's evidence; then this process
/// becomes the real `wrangler`. The build it runs caps lints at `warn`, as
/// for a Worker under a browser suite.
pub fn launch_wrangler(arguments: Vec<std::ffi::OsString>) -> i32 {
    let Some(real) = std::env::var_os(REAL_WRANGLER) else {
        eprintln!("[supercov] {WRANGLER_COMMAND} runs only as the wrangler of a measured test");
        return 127;
    };
    let watched = watched_arguments(
        arguments,
        std::env::var_os("SUPERCOV_RUST_EVIDENCE_DIR").map(PathBuf::from),
        std::env::var_os(HOOK_ENV).map(PathBuf::from),
    );
    exec_wrangler(&real, &watched.arguments, &watched.environment)
}

/// How the real `wrangler` is started.
#[derive(Debug, PartialEq)]
struct Watched {
    arguments: Vec<std::ffi::OsString>,
    environment: Vec<(String, std::ffi::OsString)>,
}

/// The arguments the real `wrangler` gets. Under a test, whose `evidence`
/// directory is named, `wrangler dev` gets an inspector port and a poller
/// writing into that directory, and loads `hook`, which tells the poller
/// where each of the session's Workers is; a remote one, a note of why it has
/// none.
fn watched_arguments(
    mut arguments: Vec<std::ffi::OsString>,
    evidence: Option<PathBuf>,
    hook: Option<PathBuf>,
) -> Watched {
    let mut environment = Vec::new();
    if starts_dev(&arguments)
        && let Some(evidence) = evidence
    {
        if runs_remote(&arguments) {
            // No poller: the run says why the Worker has no coverage.
            let _ = fs::create_dir_all(&evidence);
            let _ = fs::write(
                evidence.join(format!("{REMOTE_NOTE}{}", std::process::id())),
                "",
            );
            return Watched {
                arguments,
                environment,
            };
        }
        let port = match named_inspector_port(&arguments) {
            Some(port) => Some(port),
            None => crate::fault::or(
                "inspector-port",
                || Err("injected fault at inspector-port".to_owned()),
                free_port,
            )
            .ok()
            .inspect(|port| {
                arguments.push("--inspector-port".into());
                arguments.push(port.to_string().into());
            }),
        };
        // Neither fails short of the system running out of ports or losing
        // track of this program's own file.
        if let (Some(port), Ok(supercov)) = (
            port,
            crate::fault::io(
                "poller-executable",
                std::io::ErrorKind::NotFound,
                std::env::current_exe,
            ),
        ) {
            let windows = evidence.join(format!("worker-{}.windows", std::process::id()));
            let mut poller = std::process::Command::new(supercov);
            poller
                .arg(WRANGLER_POLL_COMMAND)
                .arg(std::process::id().to_string())
                .arg(port.to_string())
                .arg(&windows);
            if let Some(hook) = hook {
                let notes = evidence.join(format!("worker-{}.inspectors", std::process::id()));
                let _ = fs::create_dir_all(&notes);
                poller.arg(&notes);
                let inherited = std::env::var("NODE_OPTIONS").ok();
                environment.push((INSPECTORS_ENV.to_owned(), notes.into_os_string()));
                environment.push((
                    "NODE_OPTIONS".to_owned(),
                    hooked_node_options(inherited.as_deref(), &hook).into(),
                ));
            }
            // What the test's own configuration names runs inside Supercov's
            // entry, so its wasm instances can be read, wherever the
            // configuration is and whatever its `main` loads.
            let cwd = std::env::current_dir().unwrap_or_default();
            wrap_started_configs(&mut arguments, &cwd, &windows.with_extension("started"));
            let _ = poller
                .stdin(std::process::Stdio::null())
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .launch();
        }
    }
    Watched {
        arguments,
        environment,
    }
}

/// The name of what a measured `wrangler dev` is given beside a test's own
/// configuration: a copy of it whose `main` is Supercov's entry, and that
/// entry. The copy's writeback and the run's staleness pass over them.
pub(crate) const WRAPPED_PREFIX: &str = ".supercov-wrangler-";

/// Where the argument naming a configuration is, to name the copy instead:
/// the word after `-c` or `--config`, one `--config=` word, or none given.
#[derive(Debug, Clone, Copy, PartialEq)]
enum ConfigSlot {
    After(usize),
    Inline(usize),
    Default,
}

/// The configurations `wrangler dev` reads, as wrangler finds them: each one
/// `-c` or `--config` names, against `--cwd` or the directory it was started
/// in; else the first `wrangler.json`, `wrangler.jsonc` or `wrangler.toml`
/// there or in a directory above it.
fn started_configs(arguments: &[std::ffi::OsString], cwd: &Path) -> Vec<(ConfigSlot, PathBuf)> {
    let words = arguments
        .iter()
        .map(|argument| argument.to_string_lossy().into_owned())
        .collect::<Vec<_>>();
    let mut base = cwd.to_owned();
    let mut named = Vec::new();
    let mut index = 0;
    while index < words.len() {
        let word = &words[index];
        let next = words.get(index + 1);
        match (word.as_str(), next) {
            ("-c" | "--config", Some(path)) => {
                named.push((ConfigSlot::After(index + 1), PathBuf::from(path)));
                index += 1;
            }
            ("--cwd", Some(directory)) => {
                base = cwd.join(directory);
                index += 1;
            }
            _ => {
                if let Some(path) = word.strip_prefix("--config=") {
                    named.push((ConfigSlot::Inline(index), PathBuf::from(path)));
                } else if let Some(directory) = word.strip_prefix("--cwd=") {
                    base = cwd.join(directory);
                }
            }
        }
        index += 1;
    }
    if !named.is_empty() {
        return named
            .into_iter()
            .map(|(slot, path)| (slot, base.join(path)))
            .collect();
    }
    base.ancestors()
        .flat_map(|directory| {
            ["wrangler.json", "wrangler.jsonc", "wrangler.toml"].map(|name| directory.join(name))
        })
        .find(|path| path.is_file())
        .map(|path| vec![(ConfigSlot::Default, path)])
        .unwrap_or_default()
}

/// The environment `wrangler dev` picks: `-e`, `--env` or `--env=`.
fn started_environment(arguments: &[std::ffi::OsString]) -> Option<String> {
    let words = arguments
        .iter()
        .map(|argument| argument.to_string_lossy().into_owned())
        .collect::<Vec<_>>();
    words
        .iter()
        .enumerate()
        .find_map(|(index, word)| match word.as_str() {
            "-e" | "--env" => words.get(index + 1).cloned(),
            _ => word.strip_prefix("--env=").map(str::to_owned),
        })
}

/// A copy of the configuration at `path` beside it, whose `main` (the
/// environment's, where it names one) is Supercov's entry: the registry,
/// then the configuration's own `main`, whatever that module loads. Returns
/// the copy and every file written, or why the configuration was left as it
/// is.
fn wrap_config(
    path: &Path,
    environment: Option<&str>,
    number: usize,
) -> Result<(PathBuf, Vec<PathBuf>), String> {
    let (text, document) =
        read_config(path).ok_or_else(|| "it could not be read as a configuration".to_owned())?;
    let environment_main = environment
        .and_then(|name| document["env"][name]["main"].as_str())
        .map(str::to_owned);
    let main = environment_main
        .clone()
        .or_else(|| document["main"].as_str().map(str::to_owned))
        .ok_or_else(|| "it names no `main`".to_owned())?;
    let file = Path::new(&main)
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default();
    if file == ENTRY_FILE || main.contains(WRAPPED_PREFIX) {
        return Err("its `main` is Supercov's entry already".to_owned());
    }
    let directory = path.parent().unwrap_or(Path::new("."));
    let name = format!("{WRAPPED_PREFIX}{}-{number}", std::process::id());
    let folder = directory.join(&name);
    fs::create_dir_all(&folder).map_err(|error| format!("{}: {error}", folder.display()))?;
    let import = if Path::new(&main).is_absolute() {
        main.replace('\\', "/")
    } else {
        format!("../{}", main.trim_start_matches("./"))
    };
    fs::write(folder.join(REGISTRY_FILE), REGISTRY)
        .and_then(|()| {
            fs::write(
                folder.join(ENTRY_FILE),
                format!(
                    "// Generated by Supercov: the configuration's entry, with its wasm instances remembered.\nimport './{REGISTRY_FILE}';\nexport * from '{import}';\nexport {{ default }} from '{import}';\n"
                ),
            )
        })
        .map_err(|error| format!("{}: {error}", folder.display()))?;
    let entry = format!("{name}/{ENTRY_FILE}");
    let toml = path
        .extension()
        .is_some_and(|extension| extension == "toml");
    let rewritten = if toml {
        let mut document = text
            .parse::<toml_edit::DocumentMut>()
            .map_err(|error| format!("{}: {error}", path.display()))?;
        document["main"] = toml_edit::value(entry.as_str());
        if let (Some(name), Some(_)) = (environment, &environment_main) {
            document["env"][name]["main"] = toml_edit::value(entry.as_str());
        }
        document.to_string()
    } else {
        let mut document = document;
        document["main"] = json!(entry);
        if let (Some(name), Some(_)) = (environment, &environment_main) {
            document["env"][name]["main"] = json!(entry);
        }
        serde_json::to_string_pretty(&document).expect("plain data serializes")
    };
    let extension = if toml { "toml" } else { "json" };
    let copy = directory.join(format!("{name}.{extension}"));
    fs::write(&copy, rewritten).map_err(|error| format!("{}: {error}", copy.display()))?;
    Ok((copy.clone(), vec![copy, folder]))
}

/// Hand `wrangler dev` a wrapped copy of each configuration it reads, and
/// note in the test's evidence what was started and how: the run says so of
/// a Worker it could not read, and the poller removes the copies once
/// wrangler is gone.
fn wrap_started_configs(arguments: &mut Vec<std::ffi::OsString>, cwd: &Path, note: &Path) {
    let environment = started_environment(arguments);
    let mut started = Vec::new();
    let mut written = Vec::new();
    for (number, (slot, config)) in started_configs(arguments, cwd).into_iter().enumerate() {
        match wrap_config(&config, environment.as_deref(), number) {
            Ok((copy, files)) => {
                match slot {
                    ConfigSlot::After(index) => arguments[index] = copy.clone().into_os_string(),
                    ConfigSlot::Inline(index) => {
                        arguments[index] = format!("--config={}", copy.display()).into();
                    }
                    ConfigSlot::Default => {
                        arguments.push("--config".into());
                        arguments.push(copy.clone().into_os_string());
                    }
                }
                started.push(json!({"config": config, "wrapped": true}));
                written.extend(files);
            }
            Err(reason) => {
                started.push(json!({"config": config, "wrapped": false, "reason": reason}))
            }
        }
    }
    let _ = fs::write(
        note,
        json!({"configs": started, "written": written}).to_string(),
    );
}

/// What the tests that started a `wrangler dev` in `directory`, by their
/// notes, gave it: each configuration, and why one was left unwrapped.
pub fn started_worker_configs(directory: &Path) -> Vec<String> {
    let mut said = Vec::new();
    let Ok(entries) = fs::read_dir(directory) else {
        return said;
    };
    let notes = entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "started")
        });
    for path in notes {
        let Some(note) = fs::read_to_string(&path)
            .ok()
            .and_then(|text| serde_json::from_str::<Value>(&text).ok())
        else {
            continue;
        };
        for config in note["configs"].as_array().into_iter().flatten() {
            let named = config["config"].as_str().unwrap_or("?");
            said.push(match config["reason"].as_str() {
                Some(reason) => format!("`wrangler dev -c {named}`, not measured because {reason}"),
                None => format!("`wrangler dev -c {named}`"),
            });
        }
    }
    said.sort();
    said.dedup();
    said
}

/// Remove what `wrap_started_configs` wrote, by its note: each a copy or a
/// folder named by `WRAPPED_PREFIX`, and nothing else.
fn remove_wrapped(note: &Path) {
    let Some(note) = fs::read_to_string(note)
        .ok()
        .and_then(|text| serde_json::from_str::<Value>(&text).ok())
    else {
        return;
    };
    for path in note["written"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
    {
        let path = Path::new(path);
        let ours = path
            .file_name()
            .is_some_and(|name| name.to_string_lossy().starts_with(WRAPPED_PREFIX));
        if ours && path.is_dir() {
            let _ = fs::remove_dir_all(path);
        } else if ours {
            let _ = fs::remove_file(path);
        }
    }
}

/// Becomes the real `wrangler`, so the test keeps the process and the
/// signals it expects; where it cannot (Windows), runs it to its end.
fn exec_wrangler(
    real: &std::ffi::OsStr,
    arguments: &[std::ffi::OsString],
    environment: &[(String, std::ffi::OsString)],
) -> i32 {
    let rustflags = worker_rustflags(&std::env::var("RUSTFLAGS").unwrap_or_default());
    let mut command = std::process::Command::new(real);
    command
        .args(arguments)
        .env("RUSTFLAGS", rustflags)
        .envs(environment.iter().map(|(name, value)| (name, value)));
    #[cfg(unix)]
    {
        use std::os::unix::process::CommandExt;
        let error = command.exec();
        eprintln!(
            "[supercov] could not start {}: {error}",
            Path::new(&real).display()
        );
        126
    }
    #[cfg(not(unix))]
    {
        match command.launch_status() {
            Ok(status) => status.code().unwrap_or(1),
            Err(error) => {
                eprintln!(
                    "[supercov] could not start {}: {error}",
                    Path::new(&real).display()
                );
                126
            }
        }
    }
}

/// The flags the Worker's wasm build gets: the test's own, with lints capped
/// at `warn`. A cap the test inherited is dropped first: under nextest the
/// tests inherit Supercov's `--cap-lints=allow`, and with it Cargo cannot
/// learn wasm32's crate types ("output of --print=file-names missing"), even
/// with a `warn` after it.
fn worker_rustflags(inherited: &str) -> String {
    let mut kept = Vec::new();
    let mut words = inherited.split_whitespace();
    while let Some(word) = words.next() {
        if word == "--cap-lints" {
            words.next();
        } else if !word.starts_with("--cap-lints=") {
            kept.push(word);
        }
    }
    kept.extend(["--cap-lints=warn", "-A", "unused_parens"]);
    kept.join(" ")
}

/// The poller of one `wrangler dev` a test started: takes through `port`
/// while process `pid` -- that wrangler -- lives, appending to a `.part`
/// file it renames to `windows` when done, so the run knows it is whole.
pub fn poll_wrangler(arguments: Vec<std::ffi::OsString>) -> i32 {
    let (pid, port, windows, notes) = match arguments.as_slice() {
        [pid, port, windows] => (pid, port, windows, None),
        [pid, port, windows, notes] => (pid, port, windows, Some(PathBuf::from(notes))),
        _ => return 2,
    };
    let (Ok(pid), Ok(port)) = (
        pid.to_string_lossy().parse::<u32>(),
        port.to_string_lossy().parse::<u16>(),
    ) else {
        return 2;
    };
    let windows = PathBuf::from(windows);
    let part = partial(&windows);
    let poller = Poller::start(port, part.clone());
    // Each Worker of the session, into `worker-<pid>-<n>.windows`.
    let stem = windows.with_extension("");
    let others = notes.map(|notes| {
        OtherWorkers::start(notes, move |number| {
            partial(&PathBuf::from(format!(
                "{}-{number}.windows",
                stem.display()
            )))
        })
    });
    while process_alive(pid) {
        std::thread::sleep(Duration::from_millis(20));
    }
    poller.finish();
    // The wrapped copies of the test's configurations, once wrangler is done
    // with them.
    remove_wrapped(&windows.with_extension("started"));
    let parts = others.map(OtherWorkers::finish).unwrap_or_default();
    std::iter::once(part).chain(parts).for_each(|part| {
        if fs::symlink_metadata(&part).is_ok() {
            let whole = part.with_extension("");
            let _ = fs::rename(&part, &whole);
        }
    });
    0
}

fn partial(windows: &Path) -> PathBuf {
    let mut name = windows.as_os_str().to_owned();
    name.push(".part");
    PathBuf::from(name)
}

#[cfg(unix)]
fn process_alive(pid: u32) -> bool {
    let Ok(pid) = libc::pid_t::try_from(pid) else {
        return false;
    };
    // SAFETY: signal 0 only asks whether the process exists.
    let answered = unsafe { libc::kill(pid, 0) };
    answered == 0 || std::io::Error::last_os_error().raw_os_error() == Some(libc::EPERM)
}

#[cfg(not(unix))]
fn process_alive(_pid: u32) -> bool {
    false
}

/// How long the run waits for a poller to finish after its test: the poller
/// notices wrangler is gone within a few polls.
const POLLER_SETTLE: Duration = Duration::from_secs(3);

/// The Worker takes in a test's evidence directory, written out as region
/// files the run reads as it reads a native process's; and the crates they
/// came from, which `wrangler dev` built though the run's own build did not.
/// A take whose region names another instrumentation is not this run's.
pub fn materialize_worker_windows(
    directory: &Path,
    token: &str,
) -> Result<std::collections::BTreeSet<String>, String> {
    let listed = |extension: &str| -> Vec<PathBuf> {
        let mut files = fs::read_dir(directory)
            .map(|entries| {
                entries
                    .filter_map(Result::ok)
                    .map(|entry| entry.path())
                    .filter(|path| {
                        path.file_name()
                            .and_then(|name| name.to_str())
                            .is_some_and(|name| {
                                name.starts_with("worker-") && name.ends_with(extension)
                            })
                    })
                    .collect::<Vec<_>>()
            })
            .unwrap_or_default();
        files.sort();
        files
    };
    let started = Instant::now();
    while !listed(".windows.part").is_empty() && started.elapsed() < POLLER_SETTLE {
        std::thread::sleep(Duration::from_millis(20));
    }
    // A poller still writing (its wrangler outlived the test) has given what
    // it has so far: every line it wrote is whole.
    let files = listed(".windows")
        .into_iter()
        .chain(listed(".windows.part"))
        .collect::<Vec<_>>();
    let mut crates = std::collections::BTreeSet::new();
    for (number, file) in files.iter().enumerate() {
        let text =
            fs::read_to_string(file).map_err(|error| format!("{}: {error}", file.display()))?;
        for (line, value) in text
            .lines()
            .filter_map(|line| serde_json::from_str::<Value>(line).ok())
            .enumerate()
        {
            let Some(window) = window_from(&value) else {
                continue;
            };
            for (index, (crate_key, bytes)) in window.regions.into_iter().enumerate() {
                if region_token(&bytes) != Some(token) {
                    continue;
                }
                let region = directory.join(format!(
                    "{token}-worker-{number:04}-{line:06}-{index}.region"
                ));
                fs::write(&region, &bytes)
                    .map_err(|error| format!("{}: {error}", region.display()))?;
                crates.insert(crate_key);
            }
        }
        fs::remove_file(file).map_err(|error| format!("{}: {error}", file.display()))?;
    }
    Ok(crates)
}

/// The instrumentation token a region's header carries.
pub(crate) fn region_token(bytes: &[u8]) -> Option<&str> {
    let field = bytes.get(56..72)?;
    let end = field
        .iter()
        .position(|byte| *byte == 0)
        .unwrap_or(field.len());
    std::str::from_utf8(&field[..end]).ok()
}

/// The root of the Cargo workspace `directory`'s crate belongs to.
pub(crate) fn cargo_workspace_root(directory: &Path) -> Option<PathBuf> {
    let output = std::process::Command::new("cargo")
        .args(["locate-project", "--workspace", "--message-format", "plain"])
        .current_dir(directory)
        .launch_output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let manifest = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim());
    manifest.parent().map(Path::to_path_buf)
}

