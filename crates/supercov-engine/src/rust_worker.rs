//! A Rust Worker a browser suite drives through `wrangler dev`.
//!
//! The crate is instrumented in the suite's copy and `worker-build` compiles
//! it to wasm, where the region runtime keeps its region in linear memory
//! behind two exports per crate: its address and a clear. Supercov points the
//! copy's wrangler configuration at an entry module that remembers every wasm
//! instance the isolate creates, and at an inspector port of its own, so the
//! suite's own `wrangler dev` command is left as written. While the suite
//! runs, a poller takes each instance's region through the inspector and
//! clears it every few milliseconds. Each take is a window, credited by time
//! to the one browser test whose span it overlaps, as for a Go or JVM server;
//! what no single test's window holds is the run's background.

