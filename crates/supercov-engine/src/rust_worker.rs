/// Remember every wasm instance the isolate creates, for the inspector:
/// workerd answers no heap queries, so instances cannot be found later.
const REGISTRY: &str = r#"// Generated by Supercov: remembers this isolate's wasm instances.
const instances = (globalThis.__supercovWasm ??= []);
const Instance = WebAssembly.Instance;
function Recorded(module, imports) {
  const instance = new Instance(module, imports);
  instances.push(instance);
  return instance;
}
Recorded.prototype = Instance.prototype;
WebAssembly.Instance = Recorded;
const instantiate = WebAssembly.instantiate;
WebAssembly.instantiate = async function (source, imports) {
  const result = await instantiate.call(WebAssembly, source, imports);
  instances.push(result instanceof Instance ? result : result.instance);
  return result;
};
"#;

/// Evaluated in the Worker's context on every poll: each instrumented
/// crate's region as its header and the pages a probe touched since the
/// last take, then cleared. A region with nothing new is left out, except
/// the first time, which carries what `cfg!` said of the crate's gates.
const TAKE: &str = r#"(() => {
  const seen = (globalThis.__supercovTaken ??= new WeakSet());
  const out = [];
  for (const instance of globalThis.__supercovWasm ?? []) {
    const exports = instance.exports;
    for (const name of Object.keys(exports)) {
      if (!name.startsWith('__supercov_region_')) continue;
      const crate = name.slice('__supercov_region_'.length);
      const packed = BigInt.asUintN(64, BigInt(exports[name]()));
      const at = Number(packed >> 32n), length = Number(packed & 0xffffffffn);
      if (!length || !exports.memory) continue;
      const view = new DataView(exports.memory.buffer, at, length);
      const first = !seen.has(exports);
      if (!first && view.getUint32(40, true) === 0 && view.getUint32(44, true) === 0) continue;
      seen.add(exports);
      const bytes = new Uint8Array(exports.memory.buffer, at, length);
      const encode = (from, to) => {
        let text = '';
        for (let index = from; index < to; index += 0x8000)
          text += String.fromCharCode.apply(null, bytes.subarray(index, Math.min(to, index + 0x8000)));
        return btoa(text);
      };
      const bodyAt = view.getUint32(32, true);
      const segments = [[0, encode(0, bodyAt)]];
      for (let page = 0; bodyAt + page * 4096 < length; page++) {
        if (bytes[128 + (page >> 3)] & (1 << (page & 7))) {
          const from = bodyAt + page * 4096;
          segments.push([from, encode(from, Math.min(length, from + 4096))]);
        }
      }
      out.push([crate, length, segments]);
      exports['__supercov_clear_' + crate]();
    }
  }
  return out;
})()"#;

/// How often the poller takes the regions. A window shorter than the gap
/// between two tests is what lets each be credited its own.
const POLL_INTERVAL: Duration = Duration::from_millis(5);

/// A wrangler configuration Supercov can point at its entry.
#[derive(Debug, Clone, PartialEq, Eq)]
struct WorkerConfig {
    path: PathBuf,
    main: String,
    inspector_port: Option<u16>,
}

/// The wrangler configurations under `root` that build a Rust Worker: a
/// `[build] command` running `worker-build`, beside the crate's Cargo.toml.
///
/// A plain walk: a `.gitignore` above the project (a monorepo's, or the
/// checkout a fixture sits in) must not hide the project itself.
fn worker_configs(root: &Path) -> Vec<PathBuf> {
    const SKIPPED: &[&str] = &[
        "node_modules",
        "target",
        "build",
        "dist",
        ".git",
        ".supercov",
        ".wrangler",
    ];
    let mut found = Vec::new();
    let mut directories = vec![(root.to_path_buf(), 0)];
    while let Some((directory, depth)) = directories.pop() {
        let Ok(entries) = fs::read_dir(&directory) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let name = entry.file_name();
            let Some(name) = name.to_str() else {
                continue;
            };
            let Ok(kind) = entry.file_type() else {
                continue;
            };
            if kind.is_dir() {
                if depth < 6 && !SKIPPED.contains(&name) {
                    directories.push((path, depth + 1));
                }
                continue;
            }
            if !kind.is_file() || !matches!(name, "wrangler.toml" | "wrangler.json" | "wrangler.jsonc")
            {
                continue;
            }
            let builds_rust = read_config(&path).is_some_and(|(_, document)| {
                build_command(&document).is_some_and(|command| command.contains("worker-build"))
            });
            if builds_rust && path.with_file_name("Cargo.toml").is_file() {
                found.push(path);
            }
        }
    }
    found.sort();
    found
}

/// A configuration as JSON whatever it was written in.
fn read_config(path: &Path) -> Option<(String, Value)> {
    let text = fs::read_to_string(path).ok()?;
    let document = if path.extension().is_some_and(|extension| extension == "toml") {
        let table = text.parse::<toml::Table>().ok()?;
        serde_json::to_value(table).ok()?
    } else {
        serde_json::from_str(&strip_jsonc(&text)).ok()?
    };
    Some((text, document))
}

fn build_command(document: &Value) -> Option<String> {
    match document.get("build")?.get("command")? {
        Value::String(command) => Some(command.clone()),
        Value::Array(parts) => Some(
            parts
                .iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join(" "),
        ),
        _ => None,
    }
}

fn parse_config(path: &Path) -> Option<WorkerConfig> {
    let (_, document) = read_config(path)?;
    Some(WorkerConfig {
        path: path.to_owned(),
        main: document.get("main")?.as_str()?.to_owned(),
        inspector_port: document
            .get("dev")
            .and_then(|dev| dev.get("inspector_port"))
            .and_then(Value::as_u64)
            .and_then(|port| u16::try_from(port).ok()),
    })
}

/// JSON with comments and trailing commas, as wrangler.jsonc allows, made
/// plain JSON. Strings are copied as they are.
fn strip_jsonc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut characters = text.chars().peekable();
    while let Some(character) = characters.next() {
        match character {
            '"' => {
                out.push('"');
                while let Some(inner) = characters.next() {
                    out.push(inner);
                    match inner {
                        '\\' => {
                            if let Some(escaped) = characters.next() {
                                out.push(escaped);
                            }
                        }
                        '"' => break,
                        _ => {}
                    }
                }
            }
            '/' if characters.peek() == Some(&'/') => {
                for inner in characters.by_ref() {
                    if inner == '\n' {
                        out.push('\n');
                        break;
                    }
                }
            }
            '/' if characters.peek() == Some(&'*') => {
                characters.next();
                let mut previous = '\0';
                for inner in characters.by_ref() {
                    if previous == '*' && inner == '/' {
                        break;
                    }
                    previous = inner;
                }
            }
            _ => out.push(character),
        }
    }
    // A comma before a closing bracket, past any whitespace.
    let mut cleaned = String::with_capacity(out.len());
    let mut in_string = false;
    let mut escaped = false;
    let bytes = out.as_bytes();
    for (index, character) in out.char_indices() {
        if in_string {
            cleaned.push(character);
            if escaped {
                escaped = false;
            } else if character == '\\' {
                escaped = true;
            } else if character == '"' {
                in_string = false;
            }
            continue;
        }
        if character == '"' {
            in_string = true;
        } else if character == ',' {
            let next = bytes[index + 1..]
                .iter()
                .find(|byte| !byte.is_ascii_whitespace());
            if matches!(next, Some(b'}' | b']')) {
                continue;
            }
        }
        cleaned.push(character);
    }
    cleaned
}

/// Point the copy's configuration at the entry module and the inspector
/// port. The rest of the configuration is the project's.
fn rewrite_config(config: &WorkerConfig, entry: &str, port: u16) -> Result<(), String> {
    let path = &config.path;
    let text = fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))?;
    let rewritten = if path.extension().is_some_and(|extension| extension == "toml") {
        let mut document = text
            .parse::<toml_edit::DocumentMut>()
            .map_err(|error| format!("{}: {error}", path.display()))?;
        document["main"] = toml_edit::value(entry);
        if config.inspector_port.is_none() {
            if !document.contains_key("dev") {
                document["dev"] = toml_edit::table();
            }
            document["dev"]["inspector_port"] = toml_edit::value(i64::from(port));
        }
        document.to_string()
    } else {
        let mut document: Value = serde_json::from_str(&strip_jsonc(&text))
            .map_err(|error| format!("{}: {error}", path.display()))?;
        document["main"] = json!(entry);
        if config.inspector_port.is_none() {
            if !document.get("dev").is_some_and(Value::is_object) {
                document["dev"] = json!({});
            }
            document["dev"]["inspector_port"] = json!(port);
        }
        serde_json::to_string_pretty(&document).map_err(|error| error.to_string())?
    };
    fs::write(path, rewritten).map_err(|error| format!("{}: {error}", path.display()))
}

/// A port nothing listens on now.
fn free_port() -> Result<u16, String> {
    let listener = TcpListener::bind("127.0.0.1:0").map_err(|error| error.to_string())?;
    listener
        .local_addr()
        .map(|address| address.port())
        .map_err(|error| error.to_string())
}

/// The cfg values of wasm32-unknown-unknown, as the crate's own toolchain
/// reports them: what decides which items the target leaves out.
fn wasm_target_cfg(crate_directory: &Path) -> Option<crate::rust_instrumenter::TargetCfg> {
    let output = std::process::Command::new("rustc")
        .args(["--print", "cfg", "--target", "wasm32-unknown-unknown"])
        .current_dir(crate_directory)
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let values = String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|line| line.parse::<cargo_platform::Cfg>().ok())
        .collect::<Vec<_>>();
    Some(crate::rust_instrumenter::TargetCfg::new(&values))
}

fn now_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|elapsed| elapsed.as_millis() as i64)
        .unwrap_or(0)
}

/// Takes the regions of one `wrangler dev` through its inspector until told
/// to stop, appending a window per take with anything in it.
struct Poller {
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}

impl Poller {
    fn start(port: u16, windows: PathBuf) -> Self {
        let stop = Arc::new(AtomicBool::new(false));
        let flag = Arc::clone(&stop);
        let thread = std::thread::Builder::new()
            .name("supercov-worker-poller".into())
            .spawn(move || poll(port, &windows, &flag))
            .ok();
        Self { stop, thread }
    }

    /// Take once more if wrangler is still there, then stop.
    fn finish(mut self) {
        self.stop.store(true, Ordering::Release);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

impl Drop for Poller {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Release);
    }
}

fn poll(port: u16, windows: &Path, stop: &AtomicBool) {
    let Ok(mut file) = fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(windows)
    else {
        return;
    };
    let address = SocketAddr::from(([127, 0, 0, 1], port));
    // wrangler starts when the suite asks for it, and restarts the Worker on
    // a rebuild: connect, and connect again, until the run is over.
    while !stop.load(Ordering::Acquire) {
        let Ok(stream) = TcpStream::connect_timeout(&address, Duration::from_millis(200)) else {
            std::thread::sleep(Duration::from_millis(100));
            continue;
        };
        let _ = stream.set_nodelay(true);
        let _ = stream.set_read_timeout(Some(Duration::from_millis(20)));
        let Ok((mut socket, _)) =
            tungstenite::client::client(format!("ws://127.0.0.1:{port}/ws"), stream)
        else {
            std::thread::sleep(Duration::from_millis(100));
            continue;
        };
        session(&mut socket, &mut file, stop);
        let _ = socket.close(None);
    }
}

/// One inspector connection: enable the runtime, learn the Worker's
/// execution context, and take its regions on the clock. Returns when the
/// connection ends, or after the last take once the run is over.
fn session(
    socket: &mut tungstenite::WebSocket<TcpStream>,
    file: &mut fs::File,
    stop: &AtomicBool,
) {
    use tungstenite::{Error, Message};
    let send = |socket: &mut tungstenite::WebSocket<TcpStream>, message: Value| {
        socket
            .send(Message::text(message.to_string()))
            .map_err(|_| ())
    };
    if send(socket, json!({"id": 1, "method": "Runtime.enable"})).is_err() {
        return;
    }
    let mut contexts = Vec::<i64>::new();
    let mut next_id = 2_u64;
    // The take in flight: its id, when it was sent, and where its window
    // starts.
    let mut awaiting: Option<(u64, Instant)> = None;
    let mut window_start = now_ms();
    let mut last_take = Instant::now() - POLL_INTERVAL;
    let mut final_sent = false;
    loop {
        let stopping = stop.load(Ordering::Acquire);
        if stopping && awaiting.is_none() && (final_sent || contexts.is_empty()) {
            return;
        }
        if awaiting.is_none()
            && let Some(context) = contexts.last()
            && (stopping || last_take.elapsed() >= POLL_INTERVAL)
        {
            let id = next_id;
            next_id += 1;
            let request = json!({
                "id": id,
                "method": "Runtime.evaluate",
                "params": {"expression": TAKE, "contextId": context, "returnByValue": true},
            });
            if send(socket, request).is_err() {
                return;
            }
            awaiting = Some((id, Instant::now()));
            last_take = Instant::now();
            final_sent = stopping;
        }
        match socket.read() {
            Ok(Message::Text(text)) => {
                let Ok(message) = serde_json::from_str::<Value>(text.as_str()) else {
                    continue;
                };
                match message.get("method").and_then(Value::as_str) {
                    Some("Runtime.executionContextCreated") => {
                        if let Some(id) = message["params"]["context"]["id"].as_i64() {
                            contexts.push(id);
                        }
                    }
                    Some("Runtime.executionContextDestroyed") => {
                        if let Some(id) = message["params"]["executionContextId"].as_i64() {
                            contexts.retain(|context| *context != id);
                        }
                    }
                    Some("Runtime.executionContextsCleared") => contexts.clear(),
                    _ => {}
                }
                if let Some((id, _)) = awaiting
                    && message.get("id").and_then(Value::as_u64) == Some(id)
                {
                    awaiting = None;
                    let end = now_ms();
                    let regions = &message["result"]["result"]["value"];
                    if regions.as_array().is_some_and(|regions| !regions.is_empty()) {
                        let line = json!({"start": window_start, "end": end, "regions": regions});
                        let _ = writeln!(file, "{line}");
                    }
                    window_start = end;
                }
            }
            Ok(Message::Close(_)) => return,
            Ok(_) => {}
            Err(Error::Io(error))
                if matches!(
                    error.kind(),
                    std::io::ErrorKind::WouldBlock | std::io::ErrorKind::TimedOut
                ) => {}
            Err(_) => return,
        }
        // A take the Worker never answered (it was replaced mid-evaluation)
        // is given up; the next one covers the same span.
        if awaiting.is_some_and(|(_, sent)| sent.elapsed() > Duration::from_secs(5)) {
            awaiting = None;
        }
    }
}

/// One take as the poller appended it.
struct Window {
    start: i64,
    end: i64,
    /// Each region, rebuilt: crate key and bytes.
    regions: Vec<(String, Vec<u8>)>,
}

fn read_windows(directory: &Path) -> Result<Vec<Window>, String> {
    let mut files = fs::read_dir(directory)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|entry| entry.path())
                .filter(|path| path.extension().is_some_and(|extension| extension == "windows"))
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    files.sort();
    let mut windows = Vec::new();
    for file in &files {
        let text =
            fs::read_to_string(file).map_err(|error| format!("{}: {error}", file.display()))?;
        // A line cut short by Supercov being stopped mid-write is skipped.
        for line in text.lines() {
            let Ok(value) = serde_json::from_str::<Value>(line) else {
                continue;
            };
            if let Some(window) = window_from(&value) {
                windows.push(window);
            }
        }
    }
    Ok(windows)
}

fn window_from(value: &Value) -> Option<Window> {
    let mut regions = Vec::new();
    for region in value.get("regions")?.as_array()? {
        let crate_key = region.get(0)?.as_str()?.to_owned();
        let length = usize::try_from(region.get(1)?.as_u64()?).ok()?;
        let mut bytes = vec![0_u8; length];
        for segment in region.get(2)?.as_array()? {
            let offset = usize::try_from(segment.get(0)?.as_u64()?).ok()?;
            let data = base64::engine::general_purpose::STANDARD
                .decode(segment.get(1)?.as_str()?)
                .ok()?;
            bytes.get_mut(offset..offset + data.len())?.copy_from_slice(&data);
        }
        regions.push((crate_key, bytes));
    }
    Some(Window {
        start: value.get("start")?.as_i64()?,
        end: value.get("end")?.as_i64()?,
        regions,
    })
}

/// The Rust Workers of one Cargo workspace a browser suite may start.
pub struct RustWorkerServer {
    project: PreparedRustProject,
    pollers: Vec<Poller>,
    integrity: RunIntegrity,
    source_inputs: crate::source_manifest::Inputs,
    source_roots: Option<Vec<String>>,
    /// `.supercov/work/<run>/rust-worker`, holding `evidence/`.
    directory: PathBuf,
}

impl RustWorkerServer {
    /// Whether `root` holds a Rust Worker a suite could start.
    pub fn present(root: &Path) -> bool {
        !worker_configs(root).is_empty()
    }

    /// Instrument the copy's Worker crates and point their configurations at
    /// Supercov's entry, one server per Cargo workspace. Empty when the
    /// project has no Rust Worker.
    pub fn prepare(
        root: &Path,
        workspace: &Path,
        run_id: &str,
        command: &[String],
        diagnostics: &mut dyn Write,
    ) -> Result<Vec<Self>, String> {
        let configs = worker_configs(workspace);
        // Configurations by the Cargo workspace their crate belongs to: a
        // workspace is instrumented once, whatever number of Workers it holds.
        let mut by_workspace = BTreeMap::<PathBuf, Vec<WorkerConfig>>::new();
        for path in configs {
            let Some(config) = parse_config(&path) else {
                writeln!(
                    diagnostics,
                    "[supercov] {} names no `main`; its Worker is not measured",
                    path.display()
                )
                .map_err(|error| error.to_string())?;
                continue;
            };
            let crate_directory = path.parent().unwrap_or(workspace).to_owned();
            let cargo_root = cargo_workspace_root(&crate_directory).unwrap_or(crate_directory);
            by_workspace.entry(cargo_root).or_default().push(config);
        }
        let mut servers = Vec::new();
        for (index, (cargo_root, configs)) in by_workspace.into_iter().enumerate() {
            let Ok(relative) = cargo_root.strip_prefix(workspace) else {
                continue;
            };
            let original = root.join(relative);
            let source_roots = crate::source_discovery::configured_source_roots(
                &std::env::vars().collect::<BTreeMap<_, _>>(),
            );
            let mut integrity_inputs =
                crate::rust_run::collect_integrity_inputs(&original, command)?;
            for files in [
                &mut integrity_inputs.source_files,
                &mut integrity_inputs.test_files,
                &mut integrity_inputs.dependency_files,
                &mut integrity_inputs.configuration_files,
            ] {
                for file in files.iter_mut() {
                    *file = relative.join(&*file);
                }
            }
            crate::source_discovery::fold_roots_into_configuration(
                &mut integrity_inputs.execution_configuration,
                source_roots.as_deref(),
            );
            let source_inputs =
                crate::source_capture::capture(root, "rust", integrity_inputs.assertion_paths())?;
            let integrity = create_explicit_run_integrity(
                root,
                &integrity_inputs,
                &FrontendIntegrityInputs::embedded_rust(),
            )
            .map_err(|error| error.to_string())?;
            let cfg = wasm_target_cfg(&cargo_root);
            let project = crate::rust_project::prepare_rust_project_for(&cargo_root, None, cfg.as_ref())
                .map_err(|error| error.to_string())?;
            let directory = root
                .join(".supercov/work")
                .join(run_id)
                .join(format!("rust-worker-{index}"));
            let evidence = directory.join("evidence");
            fs::create_dir_all(&evidence).map_err(|error| error.to_string())?;
            let mut pollers = Vec::new();
            for (number, config) in configs.iter().enumerate() {
                let config_directory = config.path.parent().unwrap_or(&cargo_root);
                fs::write(config_directory.join(REGISTRY_FILE), REGISTRY)
                    .map_err(|error| error.to_string())?;
                let main = config.main.trim_start_matches("./");
                let entry = format!(
                    "// Generated by Supercov: the project's entry, with its wasm instances remembered.\nimport './{REGISTRY_FILE}';\nexport * from './{main}';\nexport {{ default }} from './{main}';\n"
                );
                fs::write(config_directory.join(ENTRY_FILE), entry)
                    .map_err(|error| error.to_string())?;
                let port = match config.inspector_port {
                    Some(port) => port,
                    None => free_port()?,
                };
                rewrite_config(config, ENTRY_FILE, port)?;
                pollers.push(Poller::start(
                    port,
                    evidence.join(format!("{number:04}.windows")),
                ));
            }
            servers.push(Self {
                project,
                pollers,
                integrity,
                source_inputs,
                source_roots,
                directory,
            });
        }
        Ok(servers)
    }

    pub fn source_files(&self) -> usize {
        self.project.source_files.len()
    }

    /// What the suite's environment needs: a lint on the rewritten source
    /// must not fail the Worker's build under the crate's own lint policy.
    ///
    /// Capped at `warn`, not `allow` as for `cargo test`: Cargo learns which
    /// crate types a target supports from rustc's "dropping unsupported crate
    /// type" warnings, and wasm32 drops `dylib` and `proc-macro`, so with
    /// every lint allowed it cannot read the answer and stops the build. The
    /// probes' parentheses, the one lint they raise, are allowed by name.
    pub fn environment(&self) -> BTreeMap<String, String> {
        let mut rustflags = std::env::var("RUSTFLAGS").unwrap_or_default();
        if !rustflags.is_empty() {
            rustflags.push(' ');
        }
        rustflags.push_str("--cap-lints=warn -A unused_parens");
        BTreeMap::from([("RUSTFLAGS".into(), rustflags)])
    }

    /// Publish what the Workers ran as a Rust run of its own: each window
    /// credited, by time, to the one browser test whose span it overlaps;
    /// what no single test's does is the run's background. None when no
    /// Worker ran or no browser test reported.
    pub fn publish(
        mut self,
        root: &Path,
        _evidence_run_id: &str,
        metadata: RunMetadata,
        served: &[ServedTest],
        diagnostics: &mut dyn Write,
    ) -> Result<Option<(PathBuf, RunMetadata)>, String> {
        for poller in std::mem::take(&mut self.pollers) {
            poller.finish();
        }
        let evidence_directory = self.directory.join("evidence");
        let result = self.publish_windows(root, &evidence_directory, metadata, served, diagnostics);
        let result = result.map_err(|error| {
            let run = self
                .directory
                .parent()
                .and_then(Path::file_name)
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default();
            note_kept_evidence(root, &evidence_directory, &format!("{run}-rust-worker"), error)
        });
        let _ = remove_stored_tree_deferred(root, &self.directory);
        result
    }

    fn publish_windows(
        &self,
        root: &Path,
        evidence_directory: &Path,
        metadata: RunMetadata,
        served: &[ServedTest],
        diagnostics: &mut dyn Write,
    ) -> Result<Option<(PathBuf, RunMetadata)>, String> {
        let windows = read_windows(evidence_directory)?;
        if served.is_empty() || windows.is_empty() {
            return Ok(None);
        }
        let probes = &self.project.probes;
        let mut settled = vec![0_u8; probes.cfgs.len()];
        let mut by_test = BTreeMap::<usize, Vec<Vec<RustProbeEntry>>>::new();
        let mut background = Vec::<Vec<RustProbeEntry>>::new();
        let mut overlapped = BTreeSet::new();
        for window in &windows {
            let running = served
                .iter()
                .enumerate()
                .filter(|(_, test)| {
                    test.window
                        .is_some_and(|(start, end)| start <= window.end && window.start <= end)
                })
                .map(|(index, _)| index)
                .collect::<Vec<_>>();
            let mut records = Vec::new();
            for (_, bytes) in &window.regions {
                let entries = parse_rust_region(bytes, None, &probes.token, probes)
                    .map_err(|error| error.to_string())?;
                for (slot, bits) in settled
                    .iter_mut()
                    .zip(parse_rust_region_cfgs(bytes, &probes.token, probes).unwrap_or_default())
                {
                    *slot |= bits;
                }
                if !entries.is_empty() {
                    records.push(entries);
                }
            }
            if records.is_empty() {
                continue;
            }
            match running.as_slice() {
                [owner] => by_test.entry(*owner).or_default().extend(records),
                _ => {
                    if running.len() > 1 {
                        overlapped.extend(running);
                    }
                    background.extend(records);
                }
            }
        }
        let manifest = crate::rust_test_runner::settle_cfg_gates_with(
            &self.project.manifest,
            probes,
            &settled,
            diagnostics,
        )
        .map_err(|error| error.to_string())?;
        let run_id = &metadata.id;
        let mut raw_results = Vec::new();
        for (index, test) in served.iter().enumerate() {
            let attempt_id = format!("{run_id}:worker:{index:08}");
            let credited = by_test.remove(&index);
            let attributed = credited.is_some();
            let evidence = crate::rust_test_runner::snapshot_regions(
                &manifest,
                credited.unwrap_or_default(),
                &attempt_id,
            )
            .map_err(|error| error.to_string())?;
            let test_id = format!("{}::{}", test.file, test.test_id);
            raw_results.push(RawTestResult {
                test_id: Some(test_id.clone()),
                scope: Some(ExecutionScope {
                    version: 1,
                    run_id: run_id.clone(),
                    worker_id: test.worker.clone(),
                    test_id: test_id.clone(),
                    test_key: test_id.clone(),
                    retry: test.retry,
                    attempt_id,
                }),
                test: test.name.clone(),
                test_file: Some(test.file.clone()),
                title: Some(test.title.clone()),
                retry: Some(test.retry),
                status: Some(test.status.clone()),
                expected_status: Some(test.expected_status.clone()),
                flaky: false,
                provenance: test.provenance.clone(),
                role: "test".into(),
                attribution: if attributed {
                    crate::coverage_report::ATTRIBUTION_BY_TIME
                } else {
                    crate::coverage_report::ATTRIBUTION_RUN_WIDE
                }
                .into(),
                phases: evidence.phases,
                runtime: vec![evidence.snapshot],
                browser: Vec::new(),
                server: Vec::new(),
            });
        }
        if !background.is_empty() {
            // Whether it counts turns on whether what produced it passed, as
            // for every test: the producers cannot be named, so the run is
            // asked.
            let status = if metadata.test_exit_code.unwrap_or_default() == 0 {
                "passed"
            } else {
                "failed"
            };
            let attempt_id = format!("{run_id}:worker:background");
            let evidence =
                crate::rust_test_runner::snapshot_regions(&manifest, background, &attempt_id)
                    .map_err(|error| error.to_string())?;
            let test_id = "rust::background".to_owned();
            raw_results.push(RawTestResult {
                test_id: Some(test_id.clone()),
                scope: Some(ExecutionScope {
                    version: 1,
                    run_id: run_id.clone(),
                    worker_id: "background".into(),
                    test_id: test_id.clone(),
                    test_key: test_id.clone(),
                    retry: 0,
                    attempt_id,
                }),
                test: "execution no test could be credited with".into(),
                test_file: None,
                title: None,
                retry: Some(0),
                status: Some(status.into()),
                expected_status: None,
                flaky: false,
                provenance: TestProvenance {
                    runner: "playwright".into(),
                    kind: "background".into(),
                    project: None,
                    source: "rust-owned-v1".into(),
                    tags: Vec::new(),
                },
                role: "background".into(),
                attribution: crate::coverage_report::ATTRIBUTION_EXACT.into(),
                phases: vec![CoveragePhase {
                    id: format!("{test_id}:background"),
                    kind: "background".into(),
                    operation: "execution outside any test".into(),
                    source: None,
                    caused_by_phase_id: None,
                    started_at_ms: 0,
                    ended_at_ms: Some(0),
                    status: Some(status.into()),
                    error: None,
                }]
                .into_iter()
                .chain(evidence.phases)
                .collect(),
                runtime: vec![evidence.snapshot],
                browser: Vec::new(),
                server: Vec::new(),
            });
        }
        let mut runner = crate::rust_test_runner::rust_runner_declaration("rust-libtest");
        runner.runner = "playwright".into();
        runner.execution_model = ExecutionModel::ParallelContextPropagated;
        let declaration = FrontendRunDeclaration {
            protocol_version: LANGUAGE_FRONTEND_PROTOCOL_VERSION,
            frontend_id: "rust".into(),
            frontend_version: "rust-owned-v1".into(),
            language: "rust".into(),
            structural_source: StructuralSource::OwnedProbes,
            runners: vec![runner],
            structural_limitations: crate::rust_test_runner::structural_limitations(&manifest),
        };
        let run = RustFrontendRun {
            declaration,
            request: CoverageReportRequest {
                run_id: run_id.clone(),
                manifest,
                raw_results,
                generated_at: metadata.started_at.clone(),
                coverage_model: Some(crate::rust_test_runner::rust_coverage_model()),
                integrity: None,
                test_exit_code: ExitCodeInput::Present(Some(
                    metadata.test_exit_code.unwrap_or_default(),
                )),
            },
            exit_code: metadata.test_exit_code.unwrap_or_default(),
            artifacts: 0,
            artifact_files: Vec::new(),
            build_ms: 0.0,
            execution_ms: 0.0,
        };
        validate_frontend_report_request(&run.declaration, &run.request)
            .map_err(|error| error.to_string())?;
        let archive_path = root
            .join(".supercov/work")
            .join(&metadata.id)
            .join("rust-worker-evidence.raw.gz");
        if let Some(parent) = archive_path.parent() {
            fs::create_dir_all(parent).map_err(|error| error.to_string())?;
        }
        let raw = write_archive(
            crate::source_capture::append(
                run.archive_entries().map_err(|error| error.to_string())?,
                &self.source_inputs,
            )?,
            &archive_path,
        )
        .map_err(|error| error.to_string())?;
        let credited = served
            .len()
            .saturating_sub(run.request.raw_results.iter().filter(|result| {
                result.attribution == crate::coverage_report::ATTRIBUTION_RUN_WIDE
            }).count());
        let metadata = RunMetadata {
            integrity: self.integrity.clone(),
            raw_evidence: RawEvidenceMetadata {
                schema_version: raw.schema_version,
                format: raw.format.into(),
                file: raw.file.into(),
                files: raw.files,
                uncompressed_bytes: raw.uncompressed_bytes,
                compressed_bytes: raw.compressed_bytes,
            },
            source_roots: self.source_roots.clone(),
            ..metadata
        };
        let run_directory =
            publish_run(root, &metadata, &archive_path).map_err(|error| error.to_string())?;
        writeln!(
            diagnostics,
            "[supercov] Rust Worker coverage: {} test(s), {credited} credited, across {} source file(s), credited by time",
            served.len(),
            self.project.source_files.len()
        )
        .map_err(|error| error.to_string())?;
        let overlapped = overlapped
            .into_iter()
            .filter(|index| {
                run.request.raw_results.get(*index).is_some_and(|result| {
                    result.attribution == crate::coverage_report::ATTRIBUTION_RUN_WIDE
                })
            })
            .count();
        if overlapped > 0 {
            writeln!(
                diagnostics,
                "[supercov] {overlapped} of those test(s) had the Worker's work only while another test ran too, so it is the run's and none of theirs; with `--workers=1` each test's is its own"
            )
            .map_err(|error| error.to_string())?;
        }
        Ok(Some((run_directory, metadata)))
    }
}

/// The root of the Cargo workspace `directory`'s crate belongs to.
fn cargo_workspace_root(directory: &Path) -> Option<PathBuf> {
    let output = std::process::Command::new("cargo")
        .args(["locate-project", "--workspace", "--message-format", "plain"])
        .current_dir(directory)
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let manifest = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim());
    manifest.parent().map(Path::to_path_buf)
}

