    #[test]
    fn the_copy_points_at_the_entry_and_an_inspector_port_and_keeps_the_rest() {
        let root = temporary("rewrite");
        let toml_path = root.join("wrangler.toml");
        fs::write(
            &toml_path,
            "# the Worker\nname = \"grades\"\nmain = \"build/worker/shim.mjs\"\n\n[build]\ncommand = \"worker-build --release\"\n",
        )
        .unwrap();
        let config = parse_config(&toml_path).unwrap();
        rewrite_config(&config, ENTRY_FILE, Some(9444)).unwrap();
        let rewritten = fs::read_to_string(&toml_path).unwrap();
        assert!(rewritten.contains("# the Worker"), "{rewritten}");
        let (_, document) = read_config(&toml_path).unwrap();
        assert_eq!(document["main"], ENTRY_FILE);
        assert_eq!(document["dev"]["inspector_port"], 9444);
        assert_eq!(document["build"]["command"], "worker-build --release");

        // A port the author chose is theirs, and the poller uses it.
        let json_path = root.join("wrangler.jsonc");
        fs::write(
            &json_path,
            "{\n  // mine\n  \"main\": \"./build/worker/shim.mjs\",\n  \"dev\": { \"inspector_port\": 9555 },\n}\n",
        )
        .unwrap();
        let config = parse_config(&json_path).unwrap();
        assert_eq!(config.inspector_port, Some(9555));
        assert_eq!(config.main, "./build/worker/shim.mjs");
        rewrite_config(&config, ENTRY_FILE, Some(1)).unwrap();
        let (_, document) = read_config(&json_path).unwrap();
        assert_eq!(document["main"], ENTRY_FILE);
        assert_eq!(document["dev"]["inspector_port"], 9555);
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn a_window_is_rebuilt_from_its_header_and_touched_pages() {
        let encode = |bytes: &[u8]| base64::engine::general_purpose::STANDARD.encode(bytes);
        let value = json!({
            "start": 10,
            "end": 15,
            "regions": [["abc", 8192, [[0, encode(&[1, 2, 3])], [4096, encode(&[9; 4])]]]],
        });
        let window = window_from(&value).unwrap();
        assert_eq!((window.start, window.end), (10, 15));
        let (crate_key, bytes) = &window.regions[0];
        assert_eq!(crate_key, "abc");
        assert_eq!(bytes.len(), 8192);
        assert_eq!(&bytes[..4], &[1, 2, 3, 0]);
        assert_eq!(&bytes[4096..4101], &[9, 9, 9, 9, 0]);
        // A segment past the region is a malformed window, not a panic.
        let bad = json!({"start": 0, "end": 1, "regions": [["a", 4, [[2, encode(&[1, 2, 3])]]]]});
        assert!(window_from(&bad).is_none());
    }
